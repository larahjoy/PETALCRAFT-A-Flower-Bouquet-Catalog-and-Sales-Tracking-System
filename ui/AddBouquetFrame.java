    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
     String name = txtName.getText().trim();
    String description = txtDescription.getText().trim();
    String priceText = txtPrice.getText().trim();
    String category = txtCategory.getText().trim();
    String quantityText = txtQuantity.getText().trim();

    // Validate required fields
    if (name.isEmpty() || description.isEmpty()
            || priceText.isEmpty() || category.isEmpty()
            || quantityText.isEmpty()) {
        JOptionPane.showMessageDialog(
                this, "Please fill in all fields.");
        return;
    }

    // Validate price
    double price;
    try {
        price = Double.parseDouble(priceText);

        if (!Double.isFinite(price) || price <= 0) {
            JOptionPane.showMessageDialog(
                    this, "Price must be greater than 0.");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this, "Please enter a valid price.");
        return;
    }

    // Validate quantity
    int quantity;
    try {
        quantity = Integer.parseInt(quantityText);

        if (quantity <= 0) {
            JOptionPane.showMessageDialog(
                    this, "Quantity must be greater than 0.");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this, "Please enter a valid quantity.");
        return;
    }

    // Find the selected category
    Category selectedCategory = null;

try {
    CategoryDAO categoryDAO = new CategoryDAO();

    for (Category c : categoryDAO.getAllCategories()) {
        if (c.getCategoryName().equalsIgnoreCase(category)) {
            selectedCategory = c;
            break;
        }
    }
} catch (SQLException e) {
    JOptionPane.showMessageDialog(
            this,
            "Failed to load categories:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
    );
    return;
}

if (selectedCategory == null) {
    JOptionPane.showMessageDialog(
            this,
            "Category not found.\nPlease enter an existing category."
    );
    return;
}

    // Create and save the bouquet to MySQL
    Bouquet bouquet = new Bouquet(
            0,
            name,
            description,
            price,
            selectedCategory.getCategoryId(),
            quantity
    );

    bouquet.setImagePath(selectedImagePath);

    try {
        BouquetDAO dao = new BouquetDAO();
        dao.addBouquet(bouquet);

        JOptionPane.showMessageDialog(
                this, "Bouquet added successfully!");

        // Clear the form after saving
        txtName.setText("");
        txtDescription.setText("");
        txtPrice.setText("");
        txtCategory.setText("");
        txtQuantity.setText("");

        selectedImagePath = null;
        showBouquetImage(null);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Failed to save bouquet to database:\n"
                + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnAddActionPerformed

