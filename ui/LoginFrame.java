    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed

    String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter your username and password."
        );
        return;
    }

    String sql = """
        SELECT user_id, username, password_hash, role
        FROM users
        WHERE username = ?
        """;

    try (Connection conn = DatabaseConnection.getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, username);

        try (ResultSet rs = stmt.executeQuery()) {

            if (!rs.next()
                    || !password.equals(rs.getString("password_hash"))) {
                JOptionPane.showMessageDialog(
                        this,
                        "Invalid username or password."
                );
                return;
            }

            int userId = rs.getInt("user_id");
            String accountUsername = rs.getString("username");
            String role = rs.getString("role").trim();

            DataStore.currentUserId = userId;

            if ("Admin".equalsIgnoreCase(role)) {

                MainMenuFrame menu =
                        new MainMenuFrame(accountUsername, role);

                menu.setVisible(true);
                this.dispose();

            } else if ("Staff".equalsIgnoreCase(role)) {

                MainMenuFrame menu =
                        new MainMenuFrame(accountUsername, role);

                menu.setVisible(true);
                this.dispose();

            } else {

                GuestFrame guest = new GuestFrame();
                guest.setVisible(true);
                this.dispose();
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Unable to log in:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnLoginActionPerformed

